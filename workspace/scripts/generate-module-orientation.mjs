#!/usr/bin/env node
// L17 (Track L — code quality): "One short document per module: what it
// owns, its entities, its events, its permissions, its invariants, and
// what must never happen to it — generated from code where possible so it
// cannot drift." Exit: "Every module has one. A module whose orientation
// document contradicts its code fails the documentation-truth gate."
//
// Generates docs/module-orientation/<module>.md for every real module
// under unierp-api/src/modules, purely from static analysis of the
// module's own source — no hand-written content. Sections that ARE
// mechanically derivable (entities via prisma.<Model> references, events
// via emit()/publish() calls, permissions via @Permissions(...)
// decorators, endpoint count) are generated and cannot drift, since
// regenerating always reflects current code. The "invariants / what must
// never happen" section is NOT mechanically derivable from source alone
// — stated as an explicit "needs review" placeholder rather than
// fabricated, matching this track's own established honesty precedent.
//
// The documentation-truth gate (--check mode) regenerates every doc into
// memory and diffs it against the committed file — a document that
// disagrees with a fresh regeneration is stale by definition, and fails.
//
//   node scripts/generate-module-orientation.mjs           (write all 46 docs)
//   node scripts/generate-module-orientation.mjs --check     (regenerate in memory, fail if any committed doc differs)

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const API_ROOT = existsSync(path.join(root, 'api'))
  ? path.join(root, 'api')
  : path.join(root, 'unierp-api');
const API_MODULES = path.join(API_ROOT, 'src', 'modules');
const OUT_DIR = path.join(root, 'unierp-workspace', 'docs', 'module-orientation');

const checkMode = process.argv.includes('--check');

function walk(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (entry === 'node_modules') continue;
    const full = path.join(dir, entry);
    const s = statSync(full);
    if (s.isDirectory()) walk(full, out);
    else if (entry.endsWith('.ts') && !entry.endsWith('.spec.ts')) out.push(full);
  }
  return out;
}

function generateDoc(mod) {
  const moduleDir = path.join(API_MODULES, mod);
  const files = walk(moduleDir).sort();
  const corpus = files.map((f) => readFileSync(f, 'utf-8')).join('\n');

  const entities = [...new Set([...corpus.matchAll(/prisma\.(\w+)\./g)].map((m) => m[1]))].sort();
  const events = [...new Set([...corpus.matchAll(/\.emit\(\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]))].sort();
  const permissions = [...new Set([...corpus.matchAll(/@Permissions\(\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]))].sort();
  const controllerFiles = files.filter((f) => f.endsWith('.controller.ts'));
  const serviceFiles = files.filter((f) => f.endsWith('.service.ts'));
  const endpointCount = (corpus.match(/@(Get|Post|Put|Patch|Delete)\(/g) || []).length;

  const lines = [];
  lines.push(`# ${mod} — module orientation`);
  lines.push('');
  lines.push(`Generated by \`node scripts/generate-module-orientation.mjs\` from`);
  lines.push(`\`unierp-api/src/modules/${mod}\` — never hand-edited. Regenerating this file`);
  lines.push('always reflects the current code; a committed copy that disagrees with a fresh');
  lines.push('regeneration is stale by definition (see this script\'s own `--check` mode).');
  lines.push('');
  lines.push('## What it owns');
  lines.push('');
  lines.push(`- ${files.length} source file(s): ${controllerFiles.length} controller(s), ${serviceFiles.length} service(s)`);
  lines.push(`- ${endpointCount} HTTP endpoint(s) (@Get/@Post/@Put/@Patch/@Delete)`);
  lines.push('');
  lines.push('## Entities (prisma models referenced)');
  lines.push('');
  lines.push(entities.length > 0 ? entities.map((e) => `- \`${e}\``).join('\n') : '_None found — this module does not reference prisma models directly._');
  lines.push('');
  lines.push('## Events emitted');
  lines.push('');
  lines.push(events.length > 0 ? events.map((e) => `- \`${e}\``).join('\n') : '_None found — this module does not call `.emit(...)` with a literal event name._');
  lines.push('');
  lines.push('## Permissions used');
  lines.push('');
  lines.push(permissions.length > 0 ? permissions.map((p) => `- \`${p}\``).join('\n') : '_None found — no `@Permissions(...)` decorators in this module._');
  lines.push('');
  lines.push('## Invariants — what must never happen to it');
  lines.push('');
  lines.push('_Not mechanically derivable from source alone — needs a human or a dedicated_');
  lines.push('_per-module review pass to state explicitly. Left as an honest placeholder_');
  lines.push('_rather than fabricated, matching this track\'s own established precedent_');
  lines.push('_(e.g. E01\'s row 15, L11\'s coverage-with-padding-removed section)._');
  lines.push('');

  return lines.join('\n') + '\n';
}

const modules = readdirSync(API_MODULES)
  .filter((entry) => statSync(path.join(API_MODULES, entry)).isDirectory())
  .sort();

if (checkMode) {
  const stale = [];
  const missing = [];
  for (const mod of modules) {
    const outFile = path.join(OUT_DIR, `${mod}.md`);
    const fresh = generateDoc(mod);
    if (!existsSync(outFile)) {
      missing.push(mod);
      continue;
    }
    const committed = readFileSync(outFile, 'utf-8');
    if (committed !== fresh) stale.push(mod);
  }
  console.log(`${modules.length} module(s) checked.`);
  if (missing.length > 0 || stale.length > 0) {
    console.error(`FAIL  ${missing.length} missing, ${stale.length} stale (disagree with a fresh regeneration):`);
    for (const m of missing) console.error(`  MISSING: ${m}`);
    for (const m of stale) console.error(`  STALE:   ${m}`);
    process.exit(1);
  }
  console.log('OK    every module has an orientation document, and every one matches a fresh regeneration exactly.');
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const mod of modules) {
  writeFileSync(path.join(OUT_DIR, `${mod}.md`), generateDoc(mod), 'utf-8');
}
console.log(`Wrote ${modules.length} module orientation document(s) to ${path.relative(root, OUT_DIR)}.`);
