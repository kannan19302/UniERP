#!/usr/bin/env node
// L18 (Track L — code quality): "Machine-generated, always-current maps:
// repo layer graph, module dependency graph, event flow, permission
// matrix." Exit: "Each map regenerates in CI and a stale committed copy
// fails the build. This replaces prose that describes structure — the
// class of claim that produced D004 and D013."
//
// Generates 4 markdown maps into docs/architecture/, each purely from
// static analysis of real source — no hand-written content, matching
// L17's own drift-proof pattern (--check regenerates in memory and diffs
// against the committed file).
//
//   1. module-dependency-graph.md — cross-module imports within
//      unierp-api/src/modules (a module importing another module's
//      files directly, bypassing the outbox/event pattern the platform
//      requires — a real, useful signal, not just a graph for its own
//      sake).
//   2. event-flow.md — every module's emitted events (from .emit(...)
//      calls) matched against every module's @OnEvent(...) listeners,
//      so a reader can see who produces an event and who actually
//      consumes it, cross-module.
//   3. permission-matrix.md — every module's @Permissions(...) strings,
//      one consolidated table (L17 already computed this per-module;
//      this is the same real data, presented as one cross-module view).
//   4. repo-layer-graph.md — for every repo in this checkout with a
//      package.json, its own declared dependencies on other
//      @kannan19302/* packages — the real, declared repo-to-repo
//      dependency graph, not asserted from memory.
//
//   node scripts/generate-architecture-maps.mjs           (write all 4 maps)
//   node scripts/generate-architecture-maps.mjs --check     (regenerate in memory, fail if any committed map differs)

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const API_ROOT = existsSync(path.join(root, 'api'))
  ? path.join(root, 'api')
  : path.join(root, 'unierp-api');
const API_MODULES = path.join(API_ROOT, 'src', 'modules');
const OUT_DIR = path.join(root, 'unierp-workspace', 'docs', 'architecture');

const checkMode = process.argv.includes('--check');

function walk(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (entry === 'node_modules') continue;
    const full = path.join(dir, entry);
    const s = statSync(full);
    if (s.isDirectory()) walk(full, out);
    else if (entry.endsWith('.ts') && !entry.endsWith('.spec.ts')) out.push(full);
  }
  return out;
}

const modules = readdirSync(API_MODULES)
  .filter((entry) => statSync(path.join(API_MODULES, entry)).isDirectory())
  .sort();

// Pre-compute per-module data once.
const moduleData = {};
for (const mod of modules) {
  const files = walk(path.join(API_MODULES, mod));
  const corpus = files.map((f) => readFileSync(f, 'utf-8')).join('\n');
  moduleData[mod] = {
    files,
    corpus,
    emits: [...new Set([...corpus.matchAll(/\.emit\(\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]))].sort(),
    listens: [...new Set([...corpus.matchAll(/@OnEvent\(\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]))].sort(),
    permissions: [...new Set([...corpus.matchAll(/@Permissions\(\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]))].sort(),
  };
}

// 1. Module dependency graph — cross-module relative imports.
function generateModuleDependencyGraph() {
  const edges = [];
  for (const mod of modules) {
    const relImportRe = /from\s+["']\.\.\/([a-z0-9-]+)\//g;
    const targets = new Set();
    let m;
    while ((m = relImportRe.exec(moduleData[mod].corpus))) {
      const target = m[1];
      if (modules.includes(target) && target !== mod) targets.add(target);
    }
    for (const t of [...targets].sort()) edges.push({ from: mod, to: t });
  }
  const lines = [];
  lines.push('# Module dependency graph');
  lines.push('');
  lines.push('Generated by `node scripts/generate-architecture-maps.mjs` from real');
  lines.push('`from "../other-module/..."` relative imports found in');
  lines.push('`unierp-api/src/modules/**`. A module importing another module\'s files');
  lines.push('directly bypasses the outbox/event pattern this platform requires for');
  lines.push('cross-module effects — every edge below is a real, direct coupling, worth');
  lines.push('auditing, not just a graph for its own sake.');
  lines.push('');
  lines.push(`**${edges.length} direct cross-module import edge(s) found across ${modules.length} modules.**`);
  lines.push('');
  lines.push('| From | To |');
  lines.push('| --- | --- |');
  for (const e of edges) lines.push(`| ${e.from} | ${e.to} |`);
  lines.push('');
  return lines.join('\n') + '\n';
}

// 2. Event flow — emitters matched against listeners.
function generateEventFlow() {
  const allEvents = new Set();
  for (const mod of modules) {
    for (const e of moduleData[mod].emits) allEvents.add(e);
    for (const e of moduleData[mod].listens) allEvents.add(e);
  }
  const lines = [];
  lines.push('# Event flow');
  lines.push('');
  lines.push('Generated by `node scripts/generate-architecture-maps.mjs` from real');
  lines.push('`.emit("event.name")` and `@OnEvent("event.name")` calls found in');
  lines.push('`unierp-api/src/modules/**`. An event with a producer and NO consumer is a');
  lines.push('candidate for deletion or a genuinely missing integration; an event with a');
  lines.push('consumer and NO producer in this scan is either dead listener code or');
  lines.push('produced somewhere this scan does not cover (e.g. outside `src/modules`).');
  lines.push('');
  lines.push(`**${allEvents.size} distinct event name(s) found.**`);
  lines.push('');
  lines.push('| Event | Emitted by | Listened to by |');
  lines.push('| --- | --- | --- |');
  for (const ev of [...allEvents].sort()) {
    const emitters = modules.filter((m) => moduleData[m].emits.includes(ev));
    const listeners = modules.filter((m) => moduleData[m].listens.includes(ev));
    lines.push(`| \`${ev}\` | ${emitters.join(', ') || '_none found_'} | ${listeners.join(', ') || '_none found_'} |`);
  }
  lines.push('');
  return lines.join('\n') + '\n';
}

// 3. Permission matrix — every module's permission strings, one table.
function generatePermissionMatrix() {
  const lines = [];
  lines.push('# Permission matrix');
  lines.push('');
  lines.push('Generated by `node scripts/generate-architecture-maps.mjs` from real');
  lines.push('`@Permissions("...")` decorator strings found in `unierp-api/src/modules/**`');
  lines.push('— the same real per-module data L17\'s module-orientation documents compute,');
  lines.push('presented here as one consolidated cross-module view.');
  lines.push('');
  const totalPerms = modules.reduce((s, m) => s + moduleData[m].permissions.length, 0);
  lines.push(`**${totalPerms} permission string reference(s) across ${modules.length} modules.**`);
  lines.push('');
  lines.push('| Module | Permission count | Permissions |');
  lines.push('| --- | --- | --- |');
  for (const mod of modules) {
    const perms = moduleData[mod].permissions;
    lines.push(`| ${mod} | ${perms.length} | ${perms.map((p) => `\`${p}\``).join(', ') || '_none_'} |`);
  }
  lines.push('');
  return lines.join('\n') + '\n';
}

// 4. Repo layer graph — real declared @kannan19302/* dependencies per repo.
function generateRepoLayerGraph() {
  const repoDirs = readdirSync(root).filter((entry) => {
    const full = path.join(root, entry);
    return entry.startsWith('unierp-') && statSync(full).isDirectory() && existsSync(path.join(full, 'package.json'));
  }).sort();

  const lines = [];
  lines.push('# Repo layer graph');
  lines.push('');
  lines.push('Generated by `node scripts/generate-architecture-maps.mjs` from the real');
  lines.push('`dependencies`/`devDependencies` of every repo\'s own `package.json` in this');
  lines.push('checkout, filtered to `@kannan19302/*` packages — the actual declared');
  lines.push('repo-to-repo dependency graph, not asserted from memory.');
  lines.push('');
  lines.push(`**${repoDirs.length} repo(s) with a package.json found.**`);
  lines.push('');
  lines.push('| Repo | Depends on (@kannan19302/*) |');
  lines.push('| --- | --- |');
  for (const repo of repoDirs) {
    let pkg;
    try {
      pkg = JSON.parse(readFileSync(path.join(root, repo, 'package.json'), 'utf-8'));
    } catch {
      continue;
    }
    const deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };
    const kannanDeps = Object.keys(deps).filter((d) => d.startsWith('@kannan19302/')).sort();
    lines.push(`| ${repo} | ${kannanDeps.join(', ') || '_none_'} |`);
  }
  lines.push('');
  return lines.join('\n') + '\n';
}

const generators = {
  'module-dependency-graph.md': generateModuleDependencyGraph,
  'event-flow.md': generateEventFlow,
  'permission-matrix.md': generatePermissionMatrix,
  'repo-layer-graph.md': generateRepoLayerGraph,
};

if (checkMode) {
  const stale = [];
  const missing = [];
  for (const [name, gen] of Object.entries(generators)) {
    const outFile = path.join(OUT_DIR, name);
    const fresh = gen();
    if (!existsSync(outFile)) {
      missing.push(name);
      continue;
    }
    const committed = readFileSync(outFile, 'utf-8');
    if (committed !== fresh) stale.push(name);
  }
  console.log(`${Object.keys(generators).length} map(s) checked.`);
  if (missing.length > 0 || stale.length > 0) {
    console.error(`FAIL  ${missing.length} missing, ${stale.length} stale:`);
    for (const m of missing) console.error(`  MISSING: ${m}`);
    for (const m of stale) console.error(`  STALE:   ${m}`);
    process.exit(1);
  }
  console.log('OK    every map exists and matches a fresh regeneration exactly.');
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const [name, gen] of Object.entries(generators)) {
  writeFileSync(path.join(OUT_DIR, name), gen(), 'utf-8');
}
console.log(`Wrote ${Object.keys(generators).length} architecture map(s) to ${path.relative(root, OUT_DIR)}.`);
